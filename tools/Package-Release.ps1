<#
Builds the distribution ZIP of ZtarVega from the Release build.

Usage (from the solution folder):
    powershell -ExecutionPolicy Bypass -File .\tools\Package-Release.ps1

It copies only a fixed list of files, so personal data (config.json, the database, images, logs)
can never end up in the package.
#>
param(
    [string]$ReleaseFolder = (Join-Path $PSScriptRoot '..\ZtarVega\bin\Release'),
    [string]$OutputFolder = (Join-Path $PSScriptRoot '..\dist')
)

$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.IO.Compression.FileSystem

$solutionFolder = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$ReleaseFolder = (Resolve-Path $ReleaseFolder).Path
$exePath = Join-Path $ReleaseFolder 'ZtarVega.exe'

if (-not (Test-Path $exePath)) {
    throw "ZtarVega.exe was not found in '$ReleaseFolder'. Build the Release configuration first."
}

$version = (Get-Item $exePath).VersionInfo.FileVersion
$packageName = "ZtarVega-$version"
$stageFolder = Join-Path $OutputFolder $packageName
$zipPath = "$stageFolder.zip"

if (Test-Path $stageFolder) { Remove-Item $stageFolder -Recurse -Force }
if (Test-Path $zipPath) { Remove-Item $zipPath -Force }
New-Item -ItemType Directory -Path $stageFolder -Force | Out-Null

# Program files.
Copy-Item (Join-Path $ReleaseFolder 'ZtarVega.exe') $stageFolder
Copy-Item (Join-Path $ReleaseFolder 'ZtarVega.exe.config') $stageFolder
Copy-Item (Join-Path $ReleaseFolder 'System.Data.SQLite.dll') $stageFolder

# Native SQLite library, one folder per architecture.
foreach ($architecture in 'x86', 'x64') {
    $source = Join-Path $ReleaseFolder $architecture
    if (Test-Path $source) { Copy-Item $source $stageFolder -Recurse }
}

# Languages (the template is generated by the program when it starts, so it is not needed).
$languagesSource = Join-Path $ReleaseFolder 'languages'
if (Test-Path $languagesSource) {
    Copy-Item $languagesSource $stageFolder -Recurse
    Get-ChildItem (Join-Path $stageFolder 'languages') -Filter '_template*' | Remove-Item -Force
}

# Documents.
Copy-Item (Join-Path $solutionFolder 'README.md') $stageFolder
Get-ChildItem $solutionFolder -Filter 'LICENSE*' -File | ForEach-Object { Copy-Item $_.FullName $stageFolder }

[System.IO.Compression.ZipFile]::CreateFromDirectory($stageFolder, $zipPath, [System.IO.Compression.CompressionLevel]::Optimal, $true)

Write-Host ''
Write-Host "Package created: $zipPath" -ForegroundColor Green
Write-Host ("Size: {0:N1} MB" -f ((Get-Item $zipPath).Length / 1MB))
Write-Host 'Files:'
Get-ChildItem $stageFolder -Recurse -File | ForEach-Object { Write-Host ('  ' + $_.FullName.Substring($stageFolder.Length + 1)) }